// Runs after `vite build`. Writes hosting config so that real pages return HTTP 200 and
// unknown URLs return a genuine HTTP 404 (while still showing the site's own 404 page).
//
//   dist/404.html   copy of index.html – the app renders its NotFound page for unknown URLs
//   dist/_redirects Netlify: known routes → index.html (200), everything else → 404
//   dist/.htaccess  Apache / cPanel / Hostinger: same rules
//   vercel.json     Vercel: rewrites for known routes only; unknown → dist/404.html (404)
//
// Routes are read from src/App.tsx and product slugs from src/data/products.ts, so new
// products are picked up automatically on the next build.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs'

const app = readFileSync('src/App.tsx', 'utf8')
const productsSrc = readFileSync('src/data/products.ts', 'utf8')

const pages = [...app.matchAll(/<Route path="([a-z-]+)"/g)].map((m) => m[1])
const slugs = [...productsSrc.matchAll(/slug: '([a-z0-9-]+)'/g)].map((m) => m[1])
const routes = ['/', ...pages.map((p) => `/${p}`), ...slugs.map((s) => `/products/${s}`)]

if (!pages.includes('products') || slugs.length === 0) {
  throw new Error('hosting-routes: could not read routes – check src/App.tsx and src/data/products.ts')
}

// 404 page = the app shell (React Router shows NotFound for unknown paths)
copyFileSync('dist/index.html', 'dist/404.html')

// Netlify
writeFileSync(
  'dist/_redirects',
  [
    '# generated by scripts/hosting-routes.mjs',
    ...routes.filter((r) => r !== '/').flatMap((r) => [`${r}  /index.html  200`, `${r}/  /index.html  200`]),
    '/*  /404.html  404',
    '',
  ].join('\n'),
)

// Apache / cPanel / Hostinger
const pattern = routes
  .filter((r) => r !== '/')
  .map((r) => r.slice(1).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
  .join('|')
writeFileSync(
  'dist/.htaccess',
  [
    '# generated by scripts/hosting-routes.mjs',
    'ErrorDocument 404 /404.html',
    '<IfModule mod_rewrite.c>',
    '  RewriteEngine On',
    `  RewriteRule ^(${pattern})/?$ /index.html [L]`,
    '</IfModule>',
    '',
  ].join('\n'),
)

// Vercel (read from the project root at deploy time)
writeFileSync(
  'vercel.json',
  JSON.stringify(
    {
      rewrites: routes.filter((r) => r !== '/').map((r) => ({ source: r, destination: '/index.html' })),
    },
    null,
    2,
  ) + '\n',
)

console.log(`✓ hosting routes: ${routes.length} pages (+404) → dist/_redirects, dist/.htaccess, dist/404.html, vercel.json`)
